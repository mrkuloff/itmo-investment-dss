import numpy as np

RI = {3: 0.58, 4: 0.90, 5: 1.12, 6: 1.24, 7: 1.32}

def ahp(matrix):
    m = np.array(matrix, dtype=float)
    n = m.shape[0]
    norm = m / m.sum(axis=0)          # нормализация столбцов
    w = norm.mean(axis=1)             # веса / локальные приоритеты
    lam = np.mean((m @ w) / w)        # lambda_max
    ci = (lam - n) / (n - 1)
    cr = ci / RI[n]
    return w, lam, ci, cr

# 1. Матрица сравнения критериев
crit = [[1, 3, 2, 5, 4],
        [1/3, 1, 1/2, 3, 2],
        [1/2, 2, 1, 4, 3],
        [1/5, 1/3, 1/4, 1, 1/2],
        [1/4, 1/2, 1/3, 2, 1]]

w, lam, ci, cr = ahp(crit)
print("Веса критериев:", np.round(w, 4))
print(f"lambda_max={lam:.4f}  CI={ci:.4f}  CR={cr:.4f}")

# 2. Матрицы сравнения альтернатив по каждому критерию
alts = {
 'K1': [[1, 3, 1/2, 2, 1/2], [1/3, 1, 1/4, 1/2, 1/4], [2, 4, 1, 3, 2],
        [1/2, 2, 1/3, 1, 1/3], [2, 4, 1/2, 3, 1]],
 'K2': [[1, 1, 2, 1, 2], [1, 1, 2, 1/2, 1], [1/2, 1/2, 1, 1/2, 1],
        [1, 2, 2, 1, 2], [1/2, 1, 1, 1/2, 1]],
 'K3': [[1, 1, 1/2, 1, 1/2], [1, 1, 1/2, 1, 1/3], [2, 2, 1, 2, 1],
        [1, 1, 1/2, 1, 1/2], [2, 3, 1, 2, 1]],
 'K4': [[1, 1, 2, 1, 1], [1, 1, 2, 1/2, 1/2], [1/2, 1/2, 1, 1/3, 1/2],
        [1, 2, 3, 1, 1], [1, 2, 2, 1, 1]],
 'K5': [[1, 1/2, 1, 1, 1], [2, 1, 2, 1, 1], [1, 1/2, 1, 1/2, 1],
        [1, 1, 2, 1, 1], [1, 1, 1, 1, 1]]
}

local = {}
for k, mat in alts.items():
    wa, la, cia, cra = ahp(mat)
    local[k] = wa
    print(f"{k}: локальные приоритеты={np.round(wa,4)}, CR={cra:.4f}")

# 3. Глобальные приоритеты
P = np.column_stack([local[k] for k in ['K1','K2','K3','K4','K5']])
G = P @ w
print("Глобальные приоритеты:", np.round(G, 4))
